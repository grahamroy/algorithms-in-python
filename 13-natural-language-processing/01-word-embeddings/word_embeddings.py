def plural(noun):
    if noun.endswith("s") or noun.endswith("sh"):
        return noun + "es"
    if noun.endswith("y"):
        return noun[:-1] + "ies"
    return noun + "s"


SIG = {}
for _t in TOPICS.values():
    _ns = _t["nouns"]
    for _i, _n in enumerate(_ns):
        SIG[_n] = _ns[(_i + len(_ns) // 2) % len(_ns)]
    for (_m, _f) in _t["gender"]:
        SIG[_f] = SIG[_m]        # a role is shared across gender


def gen_corpus(n_sent, rng):
    """Templated sentences with topic consistency, role signatures,
    gender agreement (his/her) and number agreement (verb + their)."""
    sents = []
    names = list(TOPICS)
    for _ in range(n_sent):
        t = TOPICS[names[rng.integers(0, 3)]]
        n1 = t["nouns"][rng.integers(0, len(t["nouns"]))]
        vs, vp = t["verbs"][rng.integers(0, len(t["verbs"]))]
        adj = t["adjs"][rng.integers(0, len(t["adjs"]))]
        n2 = SIG[n1] if rng.uniform() < 0.5 else \
            t["nouns"][rng.integers(0, len(t["nouns"]))]
        is_plur = rng.uniform() < 0.35
        if is_plur and plural(n1) not in HELD_OUT_PLURALS:
            subj, verb, poss = plural(n1), vp, "their"
        else:
            subj, verb = n1, vs
            poss = ("his" if n1 in GENDER_M else
                    "her" if n1 in GENDER_F else "the")
        obj = n2
        if rng.uniform() < 0.25 and plural(n2) not in HELD_OUT_PLURALS:
            obj = plural(n2)
        s = ["the", subj, verb, poss, obj]
        if rng.uniform() < 0.5:
            s = ["the", adj, subj, verb, poss, obj]
        sents.append(s)
    return sents


def build_vocab():
    words = list(FUNC) + ["his", "her", "their"]
    for t in TOPICS.values():
        words += t["nouns"] + t["adjs"]
        words += [v for pair in t["verbs"] for v in pair]
        words += [plural(n) for n in t["nouns"]]
    return sorted(set(w for w in words if w not in HELD_OUT_PLURALS))


def extract_pairs(sents, idx, rng, window=WINDOW):
    cs, os_ = [], []
    for s in sents:
        toks = [idx[w] for w in s]
        L = len(toks)
        for i, c in enumerate(toks):
            w = rng.integers(1, window + 1)
            for j in range(max(0, i - w), min(L, i + w + 1)):
                if j != i:
                    cs.append(c)
                    os_.append(toks[j])
    return np.array(cs), np.array(os_)


# ---------------------------------------------------------------------------
# Skip-gram with negative sampling, vectorised, hand gradients.
# ---------------------------------------------------------------------------

def sgns_pair_loss(Win, Wout, c, outs, y):
    z = Wout[outs] @ Win[c]
    p = 1 / (1 + np.exp(-np.clip(z, -30, 30)))
    return float(-(y * np.log(p + 1e-12)
                   + (1 - y) * np.log(1 - p + 1e-12)).sum())


class SGNS:
    def __init__(self, V, d=D_EMB, seed=0, lr=0.01):
        r = np.random.default_rng(seed)
        self.Win = r.uniform(-0.5, 0.5, (V, d)) / d
        self.Wout = np.zeros((V, d))
        self.lr = lr
        self.V = V

    def train(self, cs, os_, rng, p_neg, epochs=10, n_neg=N_NEG,
              batch=128):
        N = len(cs)
        for ep in range(epochs):
            perm = rng.permutation(N)
            for k in range(0, N, batch):
                b = perm[k:k + batch]
                c, o = cs[b], os_[b]
                B = len(c)
                negs = rng.choice(self.V, (B, n_neg), p=p_neg)
                outs = np.concatenate([o[:, None], negs], 1)
                v = self.Win[c]
                U = self.Wout[outs]
                z = np.einsum('bd,bkd->bk', v, U)
                p = 1 / (1 + np.exp(-np.clip(z, -30, 30)))
                y = np.zeros_like(p)
                y[:, 0] = 1
                g = p - y
                dv = np.einsum('bk,bkd->bd', g, U)
                dU = g[:, :, None] * v[:, None, :]
                np.add.at(self.Win, c, -self.lr * dv)
                np.add.at(self.Wout, outs.reshape(-1),
                          -self.lr * dU.reshape(-1, dU.shape[-1]))


def gradcheck(seed=3):
    """Audit one SGNS pair update against central differences."""
    r = np.random.default_rng(seed)
    V, d = 12, 6
    Win = r.standard_normal((V, d)) * 0.3
    Wout = r.standard_normal((V, d)) * 0.3
    c = 4
    outs = np.array([1, 7, 9])
    y = np.array([1.0, 0.0, 0.0])
    z = Wout[outs] @ Win[c]
    p = 1 / (1 + np.exp(-z))
    g = p - y
    dv = g @ Wout[outs]
    dU = g[:, None] * Win[c][None, :]
    worst = 0.0
    for ix in range(d):
        old = Win[c, ix]
        Win[c, ix] = old + 1e-6
        lp = sgns_pair_loss(Win, Wout, c, outs, y)
        Win[c, ix] = old - 1e-6
        lm = sgns_pair_loss(Win, Wout, c, outs, y)
        Win[c, ix] = old
        worst = max(worst, abs((lp - lm) / 2e-6 - dv[ix]))
    for k in range(len(outs)):
        for ix in range(d):
            old = Wout[outs[k], ix]
            Wout[outs[k], ix] = old + 1e-6
            lp = sgns_pair_loss(Win, Wout, c, outs, y)
            Wout[outs[k], ix] = old - 1e-6
            lm = sgns_pair_loss(Win, Wout, c, outs, y)
            Wout[outs[k], ix] = old
            worst = max(worst, abs((lp - lm) / 2e-6 - dU[k, ix]))
    return worst


