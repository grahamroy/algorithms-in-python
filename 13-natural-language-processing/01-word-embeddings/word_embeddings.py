def demo1(vocab, idx, sents, m):
    banner("DEMO 1 --- Predict the word next door, get a map")
    print("  The micro-language, three of its sentences:")
    print()
    for s in sents[:3]:
        print("    " + " ".join(s))
    print()
    print(f"  {len(vocab)} words, {sum(len(s) for s in sents):,} tokens,"
          f" all generated -- so the")
    print("  geometry has a ground truth. SGNS trains each word to")
    print("  predict its neighbours against 5 sampled impostors, and")
    print("  the vectors organise themselves:")
    print()
    for w in ("king", "queen", "cow", "ship", "sails", "kings"):
        print(f"    {w:8s}: {', '.join(nn_words(m.Win, vocab, idx, w))}")
    Z = norm_rows(m.Win)
    pair_sims = [float(Z[idx[a]] @ Z[idx[b]]) for a, b in GENDER_PAIRS]
    topic_sims, cross_sims = [], []
    r2 = np.random.default_rng(3)
    tn = list(TOPICS)
    for _ in range(300):
        t1, t2 = r2.choice(3, 2, replace=False)
        na = TOPICS[tn[t1]]["nouns"]
        a, b = r2.choice(len(na), 2, replace=False)
        topic_sims.append(float(Z[idx[na[a]]] @ Z[idx[na[b]]]))
        nb = TOPICS[tn[t2]]["nouns"]
        cross_sims.append(float(
            Z[idx[na[a]]] @ Z[idx[nb[r2.integers(0, len(nb))]]]))
    print()
    print(f"    mean cosine: gender partners {np.mean(pair_sims):.2f}"
          f"  >  same topic {np.mean(topic_sims):.2f}"
          f"  >  cross topic {np.mean(cross_sims):.2f}")
    print()
    print("  The constructed ordering -- partners closer than topic-")
    print("  mates, topic-mates closer than strangers -- comes back in")
    print("  the cosines. Nobody told the model about topics, gender or")
    print("  number. It was told to guess neighbours; the structure of")
    print("  use did the rest. 'You shall know a word by the company it")
    print("  keeps' (Firth, 1957), now with coordinates.")


