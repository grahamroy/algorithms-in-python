def demo3(vocab, idx, cs, os_, m):
    banner("DEMO 3 --- The theory receipt, and a tale of two matrices")
    V = len(vocab)
    C = np.zeros((V, V))
    np.add.at(C, (cs, os_), 1.0)
    tot = C.sum()
    pw_c = C.sum(1) / tot
    pw_o = C.sum(0) / tot
    mask = C > 3
    ii, jj = np.where(mask)
    pmi = np.log((C[ii, jj] / tot)
                 / (pw_c[ii] * pw_o[jj] + 1e-12) + 1e-12)
    dots = np.einsum('ij,ij->i', m.Win[ii], m.Wout[jj])
    r = np.corrcoef(pmi, dots)[0, 1]
    A = np.vstack([pmi, np.ones_like(pmi)]).T
    slope, intercept = np.linalg.lstsq(A, dots, rcond=None)[0]
    print("  Levy & Goldberg (2014): SGNS implicitly factorises the")
    print("  PMI matrix, shifted by -log k. Checked on this corpus,")
    print(f"  over every word pair seen more than 3 times:")
    print()
    print(f"    corr( PMI , win.wout ) : r = {r:.2f}")
    print(f"    slope                  : {slope:.2f}   (theory: 1)")
    print(f"    intercept              : {intercept:.2f}  "
          f"(theory: -log 5 = -1.61)")
    print()
    print("  A theorem, checked to two decimals in NumPy: the neural")
    print("  pretext and matrix factorisation are the same computation.")
    print("  GloVe factorises the counts EXPLICITLY -- weighted least")
    print("  squares on log co-occurrence. Trained here and scored")
    print("  both ways:")
    print()
    Xc = C + C.T
    nz_i, nz_j = np.where(Xc > 0)
    xv = Xc[nz_i, nz_j]
    logx = np.log(xv)
    f_w = np.minimum(1.0, (xv / 100) ** 0.75)
    rg = np.random.default_rng(5)
    d = D_EMB
    Wg = rg.uniform(-0.5, 0.5, (V, d)) / d
    Wt = rg.uniform(-0.5, 0.5, (V, d)) / d
    bg = np.zeros(V)
    bt = np.zeros(V)
    hWg = np.ones((V, d)) * 1e-8
    hWt = np.ones((V, d)) * 1e-8
    hbg = np.ones(V) * 1e-8
    hbt = np.ones(V) * 1e-8
    N = len(nz_i)
    for ep in range(300):
        perm = rg.permutation(N)
        for k in range(0, N, 512):
            b = perm[k:k + 512]
            i, j = nz_i[b], nz_j[b]
            err = (np.einsum('bd,bd->b', Wg[i], Wt[j])
                   + bg[i] + bt[j] - logx[b])
            gr = f_w[b] * err
            dWi = gr[:, None] * Wt[j]
            dWj = gr[:, None] * Wg[i]
            np.add.at(hWg, i, dWi ** 2)
            np.add.at(hWt, j, dWj ** 2)
            np.add.at(Wg, i, -0.05 * dWi / np.sqrt(hWg[i]))
            np.add.at(Wt, j, -0.05 * dWj / np.sqrt(hWt[j]))
            np.add.at(hbg, i, gr ** 2)
            np.add.at(hbt, j, gr ** 2)
            np.add.at(bg, i, -0.05 * gr / np.sqrt(hbg[i]))
            np.add.at(bt, j, -0.05 * gr / np.sqrt(hbt[j]))
    for name, W in (("input matrix W       ", Wg),
                    ("customary sum W + Wt ", Wg + Wt)):
        gg, pg = analogy_scores(W, vocab, idx)
        print(f"    GloVe, {name}: gender {gg:6.1%}  "
              f"plural {pg:6.1%}")
    print(f"    (sum's neighbours of 'king': "
          f"{', '.join(nn_words(Wg + Wt, vocab, idx, 'king')[:4])})")
    print()
    print("  The input matrix alone works; the customary W + W-tilde")
    print("  sum -- standard advice at scale -- collapses here, its")
    print("  neighbours turning into the words king CO-OCCURS with")
    print("  rather than words LIKE king. Similarity lives within each")
    print("  matrix; co-occurrence lives between them; on a small")
    print("  corpus the second swamps the first. Measure before you")
    print("  inherit even a vector sum.")


def demo4(vocab, idx, cs, os_, p_neg):
    banner("DEMO 4 --- The subword insurance (fastText)")
    print("  fastText rebuilds each word from character 3-5-grams")
    print("  (plus the whole word), and a word's vector is the mean of")
    print("  its pieces. Same pretext, same corpus:")
    print()

    def grams_of(word, gi=None):
        w = "<" + word + ">"
        gs = [w]
        for n in (3, 4, 5):
            for i in range(len(w) - n + 1):
                gs.append(w[i:i + n])
        if gi is not None:
            return [gi[g] for g in gs if g in gi]
        return gs

    all_grams = sorted(set(g for w in vocab for g in grams_of(w)))
    gi = {g: i for i, g in enumerate(all_grams)}
    G = len(all_grams)
    V = len(vocab)
    d = D_EMB
    max_g = max(len(grams_of(w)) for w in vocab)
    GPAD = np.full((V, max_g), G, dtype=int)
    GN = np.zeros(V)
    for w, i in idx.items():
        gl = grams_of(w, gi)
        GPAD[i, :len(gl)] = gl
        GN[i] = len(gl)
    rf = np.random.default_rng(7)
    Wg_ft = np.vstack([rf.uniform(-0.5, 0.5, (G, d)) / d,
                       np.zeros((1, d))])
    Wout_ft = np.zeros((V, d))
    lr_f = 0.01
    Nn = len(cs)
    for ep in range(10):
        perm = rf.permutation(Nn)
        for k in range(0, Nn, 128):
            b = perm[k:k + 128]
            c, o = cs[b], os_[b]
            B = len(c)
            negs = rf.choice(V, (B, N_NEG), p=p_neg)
            outs = np.concatenate([o[:, None], negs], 1)
            gp = GPAD[c]
            v = Wg_ft[gp].sum(1) / GN[c][:, None]
            U = Wout_ft[outs]
            z = np.einsum('bd,bkd->bk', v, U)
            pr = 1 / (1 + np.exp(-np.clip(z, -30, 30)))
            y = np.zeros_like(pr)
            y[:, 0] = 1
            gr = pr - y
            dv = np.einsum('bk,bkd->bd', gr, U) / GN[c][:, None]
            dU = gr[:, :, None] * v[:, None, :]
            np.add.at(Wg_ft, gp.reshape(-1),
                      -lr_f * np.repeat(dv, max_g, 0))
            Wg_ft[G] = 0
            np.add.at(Wout_ft, outs.reshape(-1),
                      -lr_f * dU.reshape(-1, d))

    def ft_vec(word):
        return Wg_ft[grams_of(word, gi)].mean(0)

    W_ft = np.vstack([ft_vec(w) for w in vocab])
    gf, pf = analogy_scores(W_ft, vocab, idx)
    print(f"    fastText analogies: gender {gf:6.1%}  plural {pf:6.1%}")
    print()
    print("  And the test word2vec cannot sit: three plural forms were")
    print("  held out of the corpus entirely -- no occurrences, no row,")
    print("  nothing to look up. fastText builds them from pieces:")
    print()
    Zf = norm_rows(W_ft)
    for w in HELD_OUT_PLURALS:
        v = ft_vec(w)
        v /= np.linalg.norm(v) + 1e-12
        sims = Zf @ v
        order = (-sims).argsort()
        print(f"    {w:12s} -> {', '.join(vocab[i] for i in order[:4])}")
    print()
    print("  Words it has never seen land beside their singulars and")
    print("  their families, because '<princess' and 'esses>' were")
    print("  seen, in other words. Morphology is the insurance policy:")
    print("  the reason fastText handled typos, rare words and rich")
    print("  morphologies (Finnish, Turkish) that word2vec's one-row-")
    print("  per-word ledger could not. The same instinct -- build")
    print("  words from learned pieces -- is Part 2's subject:")
    print("  tokenisation, where the pieces themselves are learned.")


