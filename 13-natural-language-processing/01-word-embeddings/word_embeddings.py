"""
word_embeddings.py --- companion code for "Word Embeddings"
(Natural Language Processing, Part 1).

Section 12 closed with four ways to manufacture supervision from
unlabelled data. This section takes that idea to its most
consequential habitat -- language -- and starts where the modern era
started: word2vec (Mikolov et al., 2013), GloVe (Pennington et al.,
2014) and fastText (Bojanowski et al., 2017). One pretext:

    predict the word next door

Skip-gram with negative sampling (SGNS) makes each word's vector
useful for guessing its neighbours and useless for guessing random
words. Nothing else. And out of that falls geometry: similar words
cluster, and directions MEAN things -- king - man + woman lands on
queen.

The stage (new for this section): a SYNTHETIC MICRO-LANGUAGE, so
every famous claim can be scored against ground truth. Three topics
(royal / farm / sea), gendered noun pairs whose gender is carried --
as in English -- by agreement (his/her possessives), regular plural
morphology carried by verb agreement (rules/rule) and 'their', and
a few plural forms held out of the corpus entirely for the
out-of-vocabulary test. 106 words, ~165k tokens, all generated by
seeded NumPy: we know exactly what the geometry SHOULD contain,
so we can measure whether it does.

Demonstrates:
  1. The map. SGNS neighbours are the right words (king -> prince,
     queen, kings...; sails -> its verb family), and cosine
     similarity reproduces the constructed ordering: gender
     partners 0.80 > same topic 0.76 > cross topic 0.23.
  2. The parallelogram. king:queen :: bull:? -> cow. Gender
     analogies 100%, plural analogies 87.5%, scored over every
     built-in quadruple -- on a corpus where the right answers
     are known by construction, not by folklore.
  3. The theory receipt. Levy & Goldberg (2014) proved SGNS
     implicitly factorises the PMI matrix shifted by log k. On
     this corpus: correlation r = 0.90, slope 0.94 (theory: 1),
     intercept -1.76 (theory: -log 5 = -1.61). A theorem checked
     to two decimals in NumPy. GloVe factorises counts EXPLICITLY
     and its input matrix scores 75%/80% -- but the customary
     W + W-tilde sum collapses to 25%/25% with co-occurring
     verbs as neighbours: similarity lives IN each matrix,
     co-occurrence lives BETWEEN them, and at toy scale the
     second swamps the first. Measure before you inherit even a
     vector sum.
  4. The subword insurance. fastText rebuilds every word from
     character n-grams (100% / 92.9% on analogies) -- and prices
     words that DO NOT EXIST in the corpus: 'princesses',
     'roosters' and 'compasses' were never generated, yet their
     n-gram vectors land beside their singulars. word2vec has no
     row to offer; morphology is the insurance.

Everything is plain NumPy, gradients hand-derived and audited.
Dependencies: numpy. Runs in about two minutes.
"""

