def norm_rows(M):
    return M / (np.linalg.norm(M, axis=1, keepdims=True) + 1e-12)


def nn_words(W, vocab, idx, w, k=5):
    Z = norm_rows(W)
    sims = Z @ Z[idx[w]]
    order = (-sims).argsort()
    return [vocab[i] for i in order[1:k + 1]]


def analogy(W, vocab, idx, a, b, c):
    Z = norm_rows(W)
    q = Z[idx[b]] - Z[idx[a]] + Z[idx[c]]
    q /= np.linalg.norm(q) + 1e-12
    sims = Z @ q
    for w in (a, b, c):
        sims[idx[w]] = -1e9
    return vocab[int(sims.argmax())]


def analogy_scores(W, vocab, idx):
    ok = total = 0
    for (a, b) in GENDER_PAIRS:
        for (c, d_) in GENDER_PAIRS:
            if (a, b) == (c, d_):
                continue
            total += 1
            ok += analogy(W, vocab, idx, a, b, c) == d_
    g = ok / total
    np_ = [n for n in ALL_NOUNS if plural(n) in idx][:8]
    ok = total = 0
    for a in np_:
        for c in np_:
            if a == c:
                continue
            total += 1
            ok += analogy(W, vocab, idx, a, plural(a), c) == plural(c)
    return g, ok / total


