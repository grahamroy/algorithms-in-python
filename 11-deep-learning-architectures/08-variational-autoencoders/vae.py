"""
vae.py --- companion code for "Variational Autoencoders"
(Deep Learning Architectures, Part 8).

Part 7's GAN generated by playing a game: no loss for the generator
was ever written down, victory was a coin-flip detective, and the
score orbited instead of descending. The variational autoencoder
(Kingma & Welling, 2014) generates from the opposite temperament:
it writes the loss down. An ENCODER maps each data point x to a
distribution over a latent code z = mu(x) + sigma(x)*eps; a DECODER
maps z back to x; and one honest objective -- the ELBO -- charges
for both reconstruction error and the information the code carries:

    loss = E[ ||x - dec(z)||^2 / (2*sigma_x^2) ]  +  beta * KL(q(z|x) || N(0,I))

The KL term is a compression bill: it prices every nat the encoder
smuggles through the latent bottleneck. The reparameterisation
trick (z written as mu + sigma*eps) is what lets gradients flow
through the sampling step.

The stage is Part 7's, on purpose: the section's two spirals with
the same real-data-anchored quality/coverage yardsticks, and the
same ring of 8 Gaussians -- plus a live retrain of Part 7's exact
GAN so the head-to-head is measured, not remembered.

Demonstrates:
  1. The honest loss, and the trade. The eval ELBO falls at every
     checkpoint -- six of six, DOWN each time -- where the GAN's
     score orbited. Head-to-head on identical yardsticks: the GAN
     is sharper (quality 98.7% vs 89.5% at 0.10; 58.0% vs 51.3% at
     0.05), the VAE covers (coverage 98.3% vs 81.7%; on the ring
     8/8 modes on every seed where Part 7's slow-detective GAN
     kept 3/8). Mode-seeking vs mode-covering, measured.
  2. The beta dial. Scaling the KL bill sweeps the model from
     autoencoder (beta 0: reconstruction mse 0.00009, useless
     prior samples) through the balanced ELBO to a generative
     sweet spot (beta 16: quality 99.8%, beating the GAN's 98.7%
     with matching sharpness) and off the cliff into posterior
     collapse (beta 64: KL 0.001 -- the latent goes silent, the
     decoder mumbles the data's mean, coverage 11.7%).
  3. The dimension ledger. Give the model 16 latent dimensions
     for 2-dimensional data and the ELBO refuses to pay for 14 of
     them: per-dimension KL comes back 1.67, 1.52, then fourteen
     zeros. The loss counts its own dimensions. And the
     reparameterisation receipt, honestly: per-sample gradient
     variance is 6x lower than REINFORCE's -- yet at this scale
     REINFORCE still trains (ELBO 4.330 vs 4.241), a folklore
     check that the trick's necessity is a matter of scale, not
     of principle.

Everything is plain NumPy, all backward passes hand-derived and
audited at startup. Dependencies: numpy. Runs in about a minute.
"""

