class GAN:
    def __init__(self, d_data=2, d_z=D_Z, hidden=HID, seed=0,
                 lr_d=1e-3, lr_g=1e-3):
        self.d_z = d_z
        self.G = Net(d_z, hidden, d_data, seed=seed, lr=lr_g)
        self.D = Net(d_data, hidden, 1, seed=seed + 100, lr=lr_d)

    def d_step(self, Xr, Xf):
        lr_, cr = self.D.forward(Xr)
        lf_, cf = self.D.forward(Xf)
        dlr = (sigmoid(lr_[:, 0]) - 1)[:, None] / len(Xr)
        dlf = sigmoid(lf_[:, 0])[:, None] / len(Xf)
        gr, _ = self.D.backward(cr, dlr)
        gf, _ = self.D.backward(cf, dlf)
        self.D.opt.step([a + b for a, b in zip(gr, gf)])

    def g_step(self, Z):
        Xf, cg = self.G.forward(Z)
        lf, cd = self.D.forward(Xf)
        dl = (sigmoid(lf[:, 0]) - 1)[:, None] / len(Z)
        _, dX = self.D.backward(cd, dl)
        gg, _ = self.G.backward(cg, dX)
        self.G.opt.step(gg)

    def sample(self, n, rng):
        return self.G.forward(rng.standard_normal((n, self.d_z)))[0]


# ---------------------------------------------------------------------------
# The VAE: encoder to (mu, logvar), reparameterised z, decoder back.
# ---------------------------------------------------------------------------

class VAE:
    def __init__(self, d_data=2, d_z=D_Z, hidden=HID, seed=0, lr=1e-3,
                 beta=1.0, sig_x=SIG_X):
        self.d_z, self.beta, self.s2 = d_z, beta, sig_x ** 2
        self.enc = Net(d_data, hidden, 2 * d_z, seed=seed, lr=lr)
        self.dec = Net(d_z, hidden, d_data, seed=seed + 100, lr=lr)

    def split(self, enc_out):
        return enc_out[:, :self.d_z], enc_out[:, self.d_z:]

    def forward(self, X, eps):
        out, ce = self.enc.forward(X)
        mu, lv = self.split(out)
        z = mu + np.exp(0.5 * lv) * eps      # the reparameterisation trick
        xhat, cd = self.dec.forward(z)
        return mu, lv, z, xhat, ce, cd

    def loss_parts(self, X, eps):
        mu, lv, z, xhat, _, _ = self.forward(X, eps)
        recon = float((((X - xhat) ** 2).sum(1) / (2 * self.s2)).mean())
        kl = float((0.5 * (mu ** 2 + np.exp(lv) - 1 - lv).sum(1)).mean())
        return recon, kl

    def loss(self, X, eps):
        r, k = self.loss_parts(X, eps)
        return r + self.beta * k

    def grads_(self, X, eps):
        n = len(X)
        mu, lv, z, xhat, ce, cd = self.forward(X, eps)
        dxhat = (xhat - X) / (self.s2 * n)
        gdec, dz = self.dec.backward(cd, dxhat)
        # through z = mu + exp(lv/2)*eps, plus the KL term's own grads
        dmu = dz + self.beta * mu / n
        dlv = dz * eps * 0.5 * np.exp(0.5 * lv) \
            + self.beta * 0.5 * (np.exp(lv) - 1) / n
        genc, _ = self.enc.backward(ce, np.concatenate([dmu, dlv], 1))
        return genc, gdec

    def step(self, X, rng):
        eps = rng.standard_normal((len(X), self.d_z))
        genc, gdec = self.grads_(X, eps)
        self.enc.opt.step(genc)
        self.dec.opt.step(gdec)

    def sample(self, n, rng):
        return self.dec.forward(rng.standard_normal((n, self.d_z)))[0]

    def reconstruct(self, X):
        out, _ = self.enc.forward(X)
        mu, _ = self.split(out)
        return self.dec.forward(mu)[0]

    def perdim_kl(self, X):
        out, _ = self.enc.forward(X)
        mu, lv = self.split(out)
        return (0.5 * (mu ** 2 + np.exp(lv) - 1 - lv)).mean(0)


def eval_elbo(v, Xev, eps_ev):
    r, k = v.loss_parts(Xev, eps_ev)
    return r + v.beta * k, r, k


# ---------------------------------------------------------------------------
# Audit: the hand backprop (encoder through the sampling step included)
# against central differences, at fixed eps.
# ---------------------------------------------------------------------------

def gradcheck(seed=3):
    rng = np.random.default_rng(seed)
    v = VAE(hidden=8, seed=seed)
    X = rng.standard_normal((6, 2))
    eps = rng.standard_normal((6, 2))
    genc, gdec = v.grads_(X, eps)
    worst = 0.0
    r = np.random.default_rng(seed + 1)
    for params, grads in ((v.enc.params, genc), (v.dec.params, gdec)):
        for P, Gr in zip(params, grads):
            flat, gflat = P.reshape(-1), Gr.reshape(-1)
            for ix in r.choice(len(flat), min(10, len(flat)),
                               replace=False):
                old = flat[ix]
                flat[ix] = old + 1e-6
                lp = v.loss(X, eps)
                flat[ix] = old - 1e-6
                lm = v.loss(X, eps)
                flat[ix] = old
                worst = max(worst, abs((lp - lm) / 2e-6 - gflat[ix]))
    return worst


