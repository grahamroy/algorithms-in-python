def demo1() -> None:
    banner("DEMO 1 --- The honest loss, and the trade")
    print("  Same stage as Part 7: draw the two spirals from noise. But")
    print("  where the GAN's score orbited, the VAE minimises one written-")
    print("  down number. Eval ELBO on a fixed held-out set, plus the")
    print("  yardsticks (quality = points within 0.10 of the curve;")
    print("  coverage = arc-bins occupied):")
    print()
    v = VAE(seed=0)
    rng = np.random.default_rng(1)
    Xev = spiral_data(2000, np.random.default_rng(96))
    eps_ev = np.random.default_rng(95).standard_normal((2000, D_Z))
    prev = None
    print("     step   elbo loss   quality   coverage")
    for s in range(6000):
        v.step(spiral_data(128, rng), rng)
        if (s + 1) % 1000 == 0:
            e, _, _ = eval_elbo(v, Xev, eps_ev)
            Xs = v.sample(2000, np.random.default_rng(99))
            q, c = spiral_metrics(Xs)
            mono = "" if prev is None else ("   DOWN" if e < prev
                                            else "   UP")
            prev = e
            print(f"    {s + 1:5d}     {e:7.3f}    {q:6.1%}     "
                  f"{c:6.1%}{mono}")
    print()
    print("  Five DOWNs out of five -- a loss you can actually watch. Now")
    print("  Part 7's exact GAN, retrained live (same seeds, same budget),")
    print("  and the real data itself, on identical yardsticks -- with a")
    print("  second, harsher quality threshold at 0.05:")
    print()
    gan = GAN(seed=0)
    grng = np.random.default_rng(1)
    for _ in range(6000):
        Xr = spiral_data(128, grng)
        Z = grng.standard_normal((128, gan.d_z))
        Xf, _ = gan.G.forward(Z)
        gan.d_step(Xr, Xf)
        gan.g_step(grng.standard_normal((128, gan.d_z)))
    Xg = gan.sample(2000, np.random.default_rng(99))
    Xs = v.sample(2000, np.random.default_rng(99))
    Xreal = spiral_data(2000, np.random.default_rng(97))
    print("                  q@0.10   q@0.05   coverage")
    for name, Xx in (("VAE          ", Xs), ("GAN (Part 7) ", Xg),
                     ("real data    ", Xreal)):
        q10, c10 = spiral_metrics(Xx)
        q5, _ = spiral_metrics(Xx, thresh=0.05)
        print(f"    {name}  {q10:6.1%}   {q5:6.1%}    {c10:6.1%}")
    print()
    print("  The trade, in numbers: the GAN is sharper -- it wins both")
    print("  quality thresholds -- and the VAE covers: 98.3% of the arc")
    print("  against the GAN's 81.7%, including tails the GAN kept losing.")
    print("  Mode-seeking versus mode-covering. Same story on Part 7's")
    print("  ring of 8 Gaussians, three seeds:")
    print()
    for seed in range(3):
        vr = VAE(seed=seed)
        r2 = np.random.default_rng(seed + 10)
        for _ in range(4000):
            vr.step(make_ring(64, r2), r2)
        Xr8 = vr.sample(2000, np.random.default_rng(99))
        m, hq, _ = ring_metrics(Xr8)
        print(f"    seed {seed}: modes {m}/8   on-mode mass {hq:.0%}")
    print()
    print("  Every seed keeps every mode (Part 7's slow-detective GAN kept")
