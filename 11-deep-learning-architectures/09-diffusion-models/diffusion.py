"""
diffusion.py --- companion code for "Diffusion Models"
(Deep Learning Architectures, Part 9).

Part 7 generated by playing a game; Part 8 wrote an honest loss and
paid for it in blur. The diffusion model (Sohl-Dickstein et al.,
2015; Ho et al., DDPM, 2020) makes a stranger bargain: it deletes
the hard half of the autoencoder. The ENCODER is fixed -- not
learned, not clever: just add Gaussian noise, T times, until the
data is static:

    x_t = sqrt(abar_t) * x_0 + sqrt(1 - abar_t) * eps

The only thing trained is the reverse direction: one network,
eps_theta(x_t, t), that looks at a noisy point and predicts the
noise in it. The loss is the simplest in this section -- plain
regression, ||eps - eps_theta||^2 -- and it is secretly Part 8's
ELBO in disguise. Sampling walks the staircase backwards: T model
passes, each removing the slice of noise the schedule added.

The stage is Parts 7-8's, on purpose: same two spirals, same ring,
same real-data-anchored yardsticks -- and the script retrains
Part 7's GAN and Part 8's VAE live, so the section's three
generative architectures meet on one measured table.

Demonstrates:
  1. The triptych. The GAN is sharp but leaves 18% of the arc
     uncovered; the VAE covers but blurs; the diffusion model,
     sampled with 20 strided passes, matches the GAN's quality at
     0.10 EXACTLY (98.7% = 98.7%) with 100.0% coverage. Sharp AND
     covering -- paid for in passes: 20 forward passes per sample
     against the GAN's and VAE's one.
  2. The bill of passes, two-sided. Walking all 100 steps scores
     WORSE (94.5%) than striding 20 (98.7%): every stochastic step
     lets an imperfect network inject its own error, so fewer,
     bigger, cleaner steps win -- measured here, and discovered at
     scale as DDIM and the sampler race. But stride too far and
     the staircase gives way: 5 passes lose 45% of coverage, 2
     passes score 0.2% -- BELOW the 40.7% a cloud of pure noise
     scores on the same yardstick. One pass returns the dataset's
     mean. The trajectory table shows why it is gradual: median
     distance to the manifold anneals 0.259 -> 0.085 -> 0.047,
     coarse shape first, fine detail last.
  3. What compute buys. On the ring at Parts 7-8's budget the
     diffusion model covers 8/8 modes on every seed but is the
     blurriest of the three (26-28% on-mode). Triple the network
     and the training and it reaches 74% -- approaching the GAN's
     81% sharpness while keeping every mode the GAN dropped.
     Diffusion converts compute into sharpness without losing
     modes; that conversion is the last five years of generative
     modelling in one sentence.

Everything is plain NumPy, all backward passes hand-derived and
audited at startup. Dependencies: numpy. Runs in about three
minutes -- the big ring model is most of the bill, and that is
the point.
"""

