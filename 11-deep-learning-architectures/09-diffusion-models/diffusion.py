# The diffusion model: fixed noising encoder, learned eps-predictor.
# ---------------------------------------------------------------------------

def make_schedule(T=T_STEPS, b0=1e-4, b1=0.25):
    betas = np.linspace(b0, b1, T)
    alphas = 1 - betas
    return betas, alphas, np.cumprod(alphas)


def t_embed(t_idx, T=T_STEPS, d=T_EMB):
    """Sinusoidal embedding of the integer timestep."""
    t = np.asarray(t_idx, dtype=float)[:, None] / T
    freqs = 2 ** np.arange(d // 2)
    ang = t * freqs[None, :] * np.pi
    return np.concatenate([np.sin(ang), np.cos(ang)], axis=1)


class Diffusion:
    def __init__(self, d_data=2, hidden=128, seed=0, lr=1e-3, T=T_STEPS,
                 b0=1e-4, b1=0.25, clip=1.3, ema=0.999):
        self.T = T
        self.betas, self.alphas, self.abar = make_schedule(T, b0, b1)
        self.clip = clip
        self.net = Net(d_data + T_EMB, hidden, d_data, seed=seed, lr=lr)
        self.ema_decay = ema
        self.ema_params = [p.copy() for p in self.net.params]

    def predict(self, Xt, t_idx, use_ema=False):
        inp = np.concatenate([Xt, t_embed(t_idx, self.T)], axis=1)
        if use_ema:
            saved = [p.copy() for p in self.net.params]
            for p, e in zip(self.net.params, self.ema_params):
                p[...] = e
            out = self.net.forward(inp)
            for p, s in zip(self.net.params, saved):
                p[...] = s
            return out
        return self.net.forward(inp)

    def loss_and_grads(self, X0, t_idx, eps):
        sa = np.sqrt(self.abar[t_idx])[:, None]
        sb = np.sqrt(1 - self.abar[t_idx])[:, None]
        Xt = sa * X0 + sb * eps                  # the whole encoder
        pred, cache = self.predict(Xt, t_idx)
        diff = pred - eps
        loss = float((diff ** 2).sum(1).mean())
        grads, _ = self.net.backward(cache, 2 * diff / len(X0))
        return loss, grads

    def step(self, X0, rng):
        t_idx = rng.integers(0, self.T, len(X0))
        eps = rng.standard_normal(X0.shape)
        loss, grads = self.loss_and_grads(X0, t_idx, eps)
        self.net.opt.step(grads)
        d = self.ema_decay                       # DDPM's quiet essential
        for e, p in zip(self.ema_params, self.net.params):
            e *= d
            e += (1 - d) * p
        return loss

    def sample(self, n, rng, n_steps=None, record_at=None, use_ema=True):
        """Ancestral sampling, optionally on a strided step subset."""
        if n_steps is None:
            steps = np.arange(self.T)
        elif n_steps == 1:
            steps = np.array([self.T - 1])
        else:
            steps = np.unique(np.linspace(0, self.T - 1, n_steps)
                              .round().astype(int))
        X = rng.standard_normal((n, 2))
        snaps = {}
        for i in range(len(steps) - 1, -1, -1):
            t = steps[i]
            t_prev = steps[i - 1] if i > 0 else -1
            ab_t = self.abar[t]
            ab_p = self.abar[t_prev] if t_prev >= 0 else 1.0
            pred, _ = self.predict(X, np.full(n, t), use_ema=use_ema)
            x0_hat = (X - np.sqrt(1 - ab_t) * pred) / np.sqrt(ab_t)
            x0_hat = np.clip(x0_hat, -self.clip, self.clip)
            if i > 0:
                beta_eff = 1 - ab_t / ab_p
                mean = (np.sqrt(ab_p) * beta_eff / (1 - ab_t) * x0_hat
                        + np.sqrt(1 - beta_eff) * (1 - ab_p) / (1 - ab_t)
                        * X)
                var = beta_eff * (1 - ab_p) / (1 - ab_t)
                X = mean + np.sqrt(var) * rng.standard_normal(X.shape)
            else:
                X = x0_hat
            if record_at is not None and t in record_at:
                snaps[t] = X.copy()
        return (X, snaps) if record_at is not None else X


