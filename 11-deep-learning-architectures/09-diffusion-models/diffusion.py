def gradcheck(seed=3):
    rng = np.random.default_rng(seed)
    d = Diffusion(hidden=8, seed=seed)
    X0 = rng.standard_normal((6, 2))
    t_idx = rng.integers(0, d.T, 6)
    eps = rng.standard_normal((6, 2))
    _, grads = d.loss_and_grads(X0, t_idx, eps)
    worst = 0.0
    r = np.random.default_rng(seed + 1)
    for P, Gr in zip(d.net.params, grads):
        flat, gflat = P.reshape(-1), Gr.reshape(-1)
        for ix in r.choice(len(flat), min(10, len(flat)), replace=False):
            old = flat[ix]
            flat[ix] = old + 1e-6
            lp, _ = d.loss_and_grads(X0, t_idx, eps)
            flat[ix] = old - 1e-6
            lm, _ = d.loss_and_grads(X0, t_idx, eps)
            flat[ix] = old
            worst = max(worst, abs((lp - lm) / 2e-6 - gflat[ix]))
    return worst


